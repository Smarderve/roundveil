String normalizeCharacterPictureName(String value) => value
    .toLowerCase()
    .replaceAll(RegExp(r'\.[a-z0-9]{2,5}$'), '')
    .replaceAll(RegExp(r'[^a-z0-9]+'), '');

CharacterPictureCatalogEntry? matchCharacterPictureCatalogFilename(
  String filename, {
  String? categoryHint,
}) {
  final normalized = normalizeCharacterPictureName(filename);
  if (normalized.isEmpty) return null;
  final matches = characterPictureCatalog
      .where((entry) {
        if (categoryHint != null && entry.category != categoryHint) {
          return false;
        }
        return <String>[
          entry.name,
          ...entry.aliases,
        ].any((name) => normalizeCharacterPictureName(name) == normalized);
      })
      .toList(growable: false);
  return matches.length == 1 ? matches.single : null;
}
